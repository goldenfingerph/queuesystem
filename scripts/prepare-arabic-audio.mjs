import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fragmentsDir = path.join(root, 'assets', 'arabic-audio');
const outputDir = path.join(root, 'public', 'audio', 'arabic');
const outputFile = path.join(outputDir, 'announcements.ogg');
const fragments = fs.readdirSync(fragmentsDir).filter((name) => /^sprite\.b64\.part\d+$/i.test(name)).sort((a,b) => Number(a.match(/part(\d+)/i)?.[1])-Number(b.match(/part(\d+)/i)?.[1]));
if (!fragments.length) throw new Error('Arabic audio source fragments are missing.');
const encoded = fragments.map((name) => fs.readFileSync(path.join(fragmentsDir,name),'utf8').trim()).join('');
if (!/^[A-Za-z0-9+/]+={0,2}$/.test(encoded)) throw new Error('Invalid Base64 in Arabic audio fragments.');
const audio = Buffer.from(encoded,'base64');
if (audio.length < 30000 || audio.subarray(0,4).toString('ascii') !== 'OggS') throw new Error('Arabic audio sprite failed OGG integrity check.');
fs.mkdirSync(outputDir,{recursive:true});
fs.writeFileSync(outputFile,audio);
console.log('Prepared Arabic TV announcement audio (' + audio.length + ' bytes): ' + outputFile);
