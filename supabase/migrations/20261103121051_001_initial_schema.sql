/*
# INFINITY SERVICES — Queue Management System: Initial Schema

## Overview
Creates all tables for a queue management system (offline-first, LAN-based).
The app has its own username/password auth (not Supabase Auth), so this is a
single-tenant schema with custom auth tables. The frontend talks directly to
the database via the Supabase anon key with RLS policies allowing access.

## Tables Created
1. `users` — Staff login accounts (admin, senior_clerk, service_officer, receptionist)
2. `services` — Service categories offered to visitors
3. `counters` — Physical counter workstations (supports 20+)
4. `counter_services` — Many-to-many: services each counter can handle
5. `staff_assignments` — Assignment of staff to counters
6. `tickets` — Queue tickets with priority and status tracking
7. `ticket_sequences` — Per-service ticket number counter (atomic)
8. `queue_events` — Audit trail for every queue state change (powers reports)
9. `visitor_categories` — Priority categories (Senior, PWD, Pregnant, Regular)
10. `system_settings` — Key/value system configuration
11. `ads` — MP4 advertisement metadata
12. `sessions` — Auth session tokens

## Security
- RLS enabled on all tables
- All tables allow `anon, authenticated` access (single-tenant app, no Supabase Auth sign-in)
- Public/shared data model — all rows visible to all users

## Seed Data
- Default admin user (username: admin, password: admin123)
- Default visitor categories (Senior, PWD, Pregnant, Regular)
- Default system settings (ticket padding, queue mode, bilingual config)
*/

-- Staff login accounts
CREATE TABLE IF NOT EXISTS users (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  display_name  text NOT NULL,
  role          text NOT NULL CHECK (role IN ('admin','senior_clerk','service_officer','receptionist')),
  is_active     integer NOT NULL DEFAULT 1,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);

-- Service categories offered to visitors
CREATE TABLE IF NOT EXISTS services (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            text NOT NULL,
  code            text NOT NULL UNIQUE,
  description     text,
  prefix          text NOT NULL,
  avg_duration_sec integer DEFAULT 300,
  is_active       integer NOT NULL DEFAULT 1,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

-- Physical counter workstations (supports 20+)
CREATE TABLE IF NOT EXISTS counters (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number     integer NOT NULL UNIQUE,
  name       text NOT NULL,
  is_active  integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Many-to-many: services each counter can handle
CREATE TABLE IF NOT EXISTS counter_services (
  counter_id integer NOT NULL REFERENCES counters(id) ON DELETE CASCADE,
  service_id integer NOT NULL REFERENCES services(id) ON DELETE CASCADE,
  PRIMARY KEY (counter_id, service_id)
);

-- Current/past assignment of a staff member to a counter
CREATE TABLE IF NOT EXISTS staff_assignments (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  counter_id integer NOT NULL REFERENCES counters(id) ON DELETE CASCADE,
  status     text NOT NULL DEFAULT 'active' CHECK (status IN ('active','break','ended')),
  started_at timestamptz NOT NULL DEFAULT now(),
  ended_at   timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_assignments_counter_status ON staff_assignments(counter_id, status);
CREATE INDEX IF NOT EXISTS idx_assignments_user ON staff_assignments(user_id);

-- Visitor categories for priority queue
CREATE TABLE IF NOT EXISTS visitor_categories (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          text NOT NULL UNIQUE,
  label_en      text NOT NULL,
  label_ar      text NOT NULL,
  priority_rank integer NOT NULL DEFAULT 0,
  is_active     integer NOT NULL DEFAULT 1,
  sort_order    integer NOT NULL DEFAULT 0
);

-- Queue tickets
CREATE TABLE IF NOT EXISTS tickets (
  id                     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number                 text NOT NULL,
  service_id             integer NOT NULL REFERENCES services(id) ON DELETE RESTRICT,
  status                 text NOT NULL DEFAULT 'waiting'
    CHECK (status IN ('waiting','called','serving','completed','no_show','transferred')),
  priority               text NOT NULL DEFAULT 'normal'
    CHECK (priority IN ('normal','priority','vip')),
  priority_rank          integer NOT NULL DEFAULT 99,
  counter_id             integer REFERENCES counters(id) ON DELETE SET NULL,
  visitor_category_id    integer REFERENCES visitor_categories(id) ON DELETE SET NULL,
  called_at              timestamptz,
  served_at              timestamptz,
  completed_at           timestamptz,
  transferred_to_service_id integer REFERENCES services(id) ON DELETE SET NULL,
  created_at             timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_tickets_service_number ON tickets(service_id, number);
CREATE INDEX IF NOT EXISTS idx_tickets_status_created ON tickets(status, created_at);
CREATE INDEX IF NOT EXISTS idx_tickets_counter ON tickets(counter_id);

-- Per-service ticket number sequence
CREATE TABLE IF NOT EXISTS ticket_sequences (
  service_id      integer PRIMARY KEY REFERENCES services(id) ON DELETE CASCADE,
  next_number     integer NOT NULL DEFAULT 1,
  last_reset_date text
);

-- Audit trail for every queue state change (powers reports)
CREATE TABLE IF NOT EXISTS queue_events (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id   integer NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  event_type  text NOT NULL CHECK (event_type IN ('created','called','recalled','started','completed','no_show','transferred')),
  counter_id  integer REFERENCES counters(id) ON DELETE SET NULL,
  user_id     integer REFERENCES users(id) ON DELETE SET NULL,
  from_status text,
  to_status   text,
  meta        text,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_events_ticket ON queue_events(ticket_id);
CREATE INDEX IF NOT EXISTS idx_events_created ON queue_events(created_at);

-- Key/value system configuration
CREATE TABLE IF NOT EXISTS system_settings (
  key         text PRIMARY KEY,
  value       text,
  updated_at  timestamptz NOT NULL DEFAULT now()
);

-- Uploaded MP4 advertisement metadata
CREATE TABLE IF NOT EXISTS ads (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  filename      text NOT NULL UNIQUE,
  original_name text NOT NULL,
  duration_sec  integer,
  is_active     integer NOT NULL DEFAULT 1,
  sort_order    integer NOT NULL DEFAULT 0,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- Session tokens for authenticated staff
CREATE TABLE IF NOT EXISTS sessions (
  token       text PRIMARY KEY,
  user_id     integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at  timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);

