-- v2: auth sessions, visitor categories, ticket numbering, priority config
-- Preserves all v1 tables and data. Adds new tables and columns safely.

-- Session tokens for authenticated staff (server-side, not localStorage)
CREATE TABLE IF NOT EXISTS sessions (
  token       TEXT PRIMARY KEY,
  user_id     INTEGER NOT NULL,
  created_at  TEXT NOT NULL DEFAULT (datetime('now')),
  expires_at  TEXT NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);

-- Visitor categories for priority queue (Senior Citizen, PWD, Pregnant Woman, Regular)
CREATE TABLE IF NOT EXISTS visitor_categories (
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  code          TEXT NOT NULL UNIQUE,
  label_en      TEXT NOT NULL,
  label_ar      TEXT NOT NULL,
  priority_rank INTEGER NOT NULL DEFAULT 0,
  is_active     INTEGER NOT NULL DEFAULT 1,
  sort_order    INTEGER NOT NULL DEFAULT 0
);

